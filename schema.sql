create temporary table legacy_coach_id_map (
  legacy_id text primary key,
  new_id bigint not null
) on commit drop;

create temporary table legacy_payroll_id_map (
  legacy_id text primary key,
  new_id bigint not null
) on commit drop;

-- Migrate legacy IDs through temporary maps because UUIDs cannot be cast to bigint.
do $$
declare
  old_coach record;
  old_schedule record;
  old_payroll record;
  new_coach_id bigint;
  new_payroll_id bigint;
begin
  if to_regclass('public.coaches') is not null then
    for old_coach in execute
      'select id, full_name, phone, hourly_rate from public.coaches'
    loop
      insert into public.coach (nama_coach, alamat, no_telepon, tarif_per_sesi)
      values (old_coach.full_name, null, old_coach.phone, old_coach.hourly_rate)
      returning id_coach into new_coach_id;
      insert into legacy_coach_id_map (legacy_id, new_id)
      values (old_coach.id::text, new_coach_id);
    end loop;
  end if;

  if to_regclass('public.attendance') is not null then
    for old_schedule in execute
      'select a.*, to_jsonb(a) as legacy_row from public.attendance a'
    loop
      select new_id into new_coach_id
      from legacy_coach_id_map
      where legacy_id = old_schedule.coach_id::text;
      if new_coach_id is null then
        raise exception 'Coach % pada data kehadiran lama tidak ditemukan.', old_schedule.coach_id;
      end if;
      insert into public.jadwal_mengajar (
        id_coach, tanggal_mengajar, jam_mengajar, jumlah_sesi, status_kehadiran
      ) values (
        new_coach_id,
        old_schedule.work_date,
        coalesce(nullif(old_schedule.legacy_row->>'session_start', '')::time, time '09:00'),
        greatest(1, ceil(coalesce(nullif(old_schedule.legacy_row->>'hours', '')::numeric, 1)))::integer,
        case coalesce(old_schedule.legacy_row->>'session_status', 'completed')
          when 'scheduled' then 'Dijadwalkan'
          when 'cancelled' then 'Tidak Hadir'
          else 'Hadir'
        end
      );
    end loop;
  end if;

  if to_regclass('public.payrolls') is not null then
    for old_payroll in execute
      'select p.*, to_jsonb(p) as legacy_row from public.payrolls p'
    loop
      select new_id into new_coach_id
      from legacy_coach_id_map
      where legacy_id = old_payroll.coach_id::text;
      if new_coach_id is null then
        raise exception 'Coach % pada data penggajian lama tidak ditemukan.', old_payroll.coach_id;
      end if;

      insert into public.penggajian (
        id_coach, periode_gaji, total_sesi, total_honor, potongan, status_penggajian
      ) values (
        new_coach_id,
        old_payroll.period_start::text || '|' || old_payroll.period_end::text,
        greatest(1, ceil(old_payroll.total_hours))::integer,
        old_payroll.total_amount,
        0,
        case old_payroll.status when 'paid' then 'Dibayar' else 'Belum Dibayar' end
      )
      returning id_penggajian into new_payroll_id;
      insert into legacy_payroll_id_map (legacy_id, new_id)
      values (old_payroll.id::text, new_payroll_id);

      if old_payroll.status = 'paid' and old_payroll.total_amount > 0 then
        insert into public.pembayaran (
          id_penggajian, tanggal_pembayaran, jumlah_pembayaran, metode_pembayaran, keterangan
        ) values (
          new_payroll_id,
          coalesce(nullif(old_payroll.legacy_row->>'paid_at', '')::timestamptz::date,
                   nullif(old_payroll.legacy_row->>'created_at', '')::timestamptz::date,
                   old_payroll.period_end),
          old_payroll.total_amount,
          'Migrasi data sebelumnya',
          'Pembayaran payroll yang sudah berstatus paid sebelum migrasi.'
        );
      end if;
    end loop;
  end if;
end;
$$;

