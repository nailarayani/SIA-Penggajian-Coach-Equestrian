create or replace function public.create_payroll_payment(
  p_payroll_id bigint,
  p_payment_date date,
  p_payment_method text,
  p_payment_note text default null
)
returns jsonb
language plpgsql
set search_path = public
as $$
declare
  v_payroll public.penggajian%rowtype;
  v_paid numeric(14, 2);
  v_due numeric(14, 2);
  v_payment public.pembayaran%rowtype;
begin
  select * into v_payroll
  from public.penggajian
  where id_penggajian = p_payroll_id
  for update;

  if not found then
    raise exception using errcode = 'P0002', message = 'Data penggajian tidak ditemukan.';
  end if;
  if p_payment_date is null or nullif(trim(p_payment_method), '') is null then
    raise exception using errcode = '22023', message = 'Tanggal dan metode pembayaran wajib diisi.';
  end if;

  select coalesce(sum(jumlah_pembayaran), 0) into v_paid
  from public.pembayaran
  where id_penggajian = p_payroll_id;
  v_due := v_payroll.gaji_bersih - v_paid;
  if v_due <= 0 then
    raise exception using errcode = '22023', message = 'Penggajian ini sudah lunas.';
  end if;

  insert into public.pembayaran (
    id_penggajian, tanggal_pembayaran, jumlah_pembayaran, metode_pembayaran, keterangan
  ) values (
    p_payroll_id, p_payment_date, v_due, trim(p_payment_method), p_payment_note
  )
  returning * into v_payment;

  update public.penggajian
  set status_penggajian = 'Dibayar'
  where id_penggajian = p_payroll_id;

  return jsonb_build_object('payment', to_jsonb(v_payment), 'payroll', to_jsonb(v_payroll));
end;
$$;

