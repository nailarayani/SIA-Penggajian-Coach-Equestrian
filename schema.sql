create or replace function public.create_payroll(
  p_coach_id bigint,
  p_period_start date,
  p_period_end date,
  p_potongan numeric default 0
)
returns jsonb
language plpgsql
set search_path = public
as $$
declare
  v_coach public.coach%rowtype;
  v_total_sessions integer;
  v_total_honor numeric(14, 2);
  v_payroll public.penggajian%rowtype;
  v_period text;
begin
  if p_period_start is null or p_period_end is null or p_period_start > p_period_end then
    raise exception using errcode = '22023', message = 'Rentang tanggal penggajian tidak valid.';
  end if;
  if p_potongan is null or p_potongan < 0 then
    raise exception using errcode = '22023', message = 'Potongan tidak boleh negatif.';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(
    p_coach_id::text || ':' || p_period_start::text || ':' || p_period_end::text, 0
  ));

  select * into v_coach from public.coach where id_coach = p_coach_id;
  if not found then
    raise exception using errcode = 'P0002', message = 'Coach tidak ditemukan.';
  end if;

  select
    coalesce(sum(jumlah_sesi), 0)::integer,
    coalesce(sum(jumlah_sesi * v_coach.tarif_per_sesi), 0)
  into v_total_sessions, v_total_honor
  from public.jadwal_mengajar
  where id_coach = p_coach_id
    and tanggal_mengajar between p_period_start and p_period_end
    and status_kehadiran = 'Hadir'
    and not exists (
      select 1
      from public.penggajian existing
      cross join lateral (
        select to_jsonb(existing)->>'periode_gaji' as periode
      ) existing_period
      where existing.id_coach = p_coach_id
        and daterange(
          case
            when position('|' in existing_period.periode) > 0
              then split_part(existing_period.periode::text, '|'::text, 1)::date
            else existing_period.periode::date
          end,
          case
            when position('|' in existing_period.periode) > 0
              then split_part(existing_period.periode::text, '|'::text, 2)::date
            else existing_period.periode::date
          end,
          '[]'
        ) @> jadwal_mengajar.tanggal_mengajar
    );

  if v_total_sessions = 0 then
    raise exception using errcode = '22023', message = 'Tidak ada sesi hadir yang belum digaji pada periode ini.';
  end if;
  if p_potongan > v_total_honor then
    raise exception using errcode = '22023', message = 'Potongan tidak boleh melebihi total honor.';
  end if;

  v_period := p_period_start::text || '|' || p_period_end::text;
  insert into public.penggajian (
    id_coach, periode_gaji, total_sesi, total_honor, potongan, status_penggajian
  ) values (
    p_coach_id, v_period, v_total_sessions, v_total_honor, p_potongan, 'Belum Dibayar'
  )
  returning * into v_payroll;

  return to_jsonb(v_payroll);
exception
  when unique_violation then
    raise exception using errcode = '23505', message = 'Penggajian untuk coach dan periode tersebut sudah dibuat.';
end;
$$;

