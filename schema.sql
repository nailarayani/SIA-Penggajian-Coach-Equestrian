create table if not exists public.coach (
  id_coach bigint generated by default as identity primary key,
  nama_coach text not null check (char_length(trim(nama_coach)) between 1 and 120),
  alamat text,
  no_telepon text,
  tarif_per_sesi numeric(14, 2) not null check (tarif_per_sesi >= 0)
);

create table if not exists public.jadwal_mengajar (
  id_jadwal bigint generated by default as identity primary key,
  id_coach bigint not null references public.coach(id_coach) on delete restrict,
  tanggal_mengajar date not null,
  jam_mengajar time not null,
  jumlah_sesi integer not null check (jumlah_sesi > 0),
  status_kehadiran text not null default 'Hadir'
    check (status_kehadiran in ('Dijadwalkan', 'Hadir', 'Tidak Hadir'))
);

alter table public.jadwal_mengajar
  drop constraint if exists jadwal_mengajar_status_kehadiran_check;

update public.jadwal_mengajar
set status_kehadiran = case lower(trim(status_kehadiran))
  when 'hadir' then 'Hadir'
  when 'present' then 'Hadir'
  when 'completed' then 'Hadir'
  when 'selesai' then 'Hadir'
  when 'dijadwalkan' then 'Dijadwalkan'
  when 'scheduled' then 'Dijadwalkan'
  when 'terjadwal' then 'Dijadwalkan'
  when 'tidak hadir' then 'Tidak Hadir'
  when 'tidak_hadir' then 'Tidak Hadir'
  when 'absent' then 'Tidak Hadir'
  when 'cancelled' then 'Tidak Hadir'
  when 'canceled' then 'Tidak Hadir'
  when 'batal' then 'Tidak Hadir'
  else status_kehadiran
end
where status_kehadiran not in ('Dijadwalkan', 'Hadir', 'Tidak Hadir');

do $$
declare
  invalid_statuses text;
begin
  select string_agg(distinct status_kehadiran, ', ')
  into invalid_statuses
  from public.jadwal_mengajar
  where status_kehadiran not in ('Dijadwalkan', 'Hadir', 'Tidak Hadir');

  if invalid_statuses is not null then
    raise exception 'Status kehadiran lama belum didukung: %. Ubah nilainya menjadi Dijadwalkan, Hadir, atau Tidak Hadir lalu jalankan ulang skema.', invalid_statuses;
  end if;
end;
$$;

alter table public.jadwal_mengajar
  add constraint jadwal_mengajar_status_kehadiran_check
  check (status_kehadiran in ('Dijadwalkan', 'Hadir', 'Tidak Hadir'));

create table if not exists public.penggajian (
  id_penggajian bigint generated by default as identity primary key,
  id_coach bigint not null references public.coach(id_coach) on delete restrict,
  periode_gaji text not null,
  total_sesi integer not null check (total_sesi > 0),
  total_honor numeric(14, 2) not null check (total_honor >= 0),
  potongan numeric(14, 2) not null default 0 check (potongan >= 0 and potongan <= total_honor),
  gaji_bersih numeric(14, 2) generated always as (total_honor - potongan) stored,
  status_penggajian text not null default 'Belum Dibayar'
    check (status_penggajian in ('Belum Dibayar', 'Dibayar')),
  unique (id_coach, periode_gaji)
);

alter table public.penggajian
  drop constraint if exists penggajian_status_penggajian_check;
alter table public.penggajian
  alter column status_penggajian set default 'Belum Dibayar';
alter table public.penggajian
  add constraint penggajian_status_penggajian_check
  check (status_penggajian in ('Belum Dibayar', 'Dibayar')) not valid;

do $$
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'penggajian'
      and column_name = 'gaji_bersih'
      and is_generated = 'NEVER'
  ) then
    alter table public.penggajian drop column gaji_bersih;
    alter table public.penggajian
      add column gaji_bersih numeric(14, 2)
      generated always as (total_honor - potongan) stored;
  end if;
end;
$$;

do $$
declare
  period_type text;
  old_constraint record;
begin
  select data_type
  into period_type
  from information_schema.columns
  where table_schema = 'public'
    and table_name = 'penggajian'
    and column_name = 'periode_gaji';

  if period_type = 'date' then
    for old_constraint in
      select conname
      from pg_constraint
      where conrelid = 'public.penggajian'::regclass
        and contype = 'c'
        and pg_get_constraintdef(oid) ilike '%periode_gaji%'
    loop
      execute format(
        'alter table public.penggajian drop constraint %I',
        old_constraint.conname
      );
    end loop;

    alter table public.penggajian
      alter column periode_gaji type text
      using periode_gaji::text;
  end if;
end;
$$;

create table if not exists public.pembayaran (
  id_pembayaran bigint generated by default as identity primary key,
  id_penggajian bigint not null references public.penggajian(id_penggajian) on delete restrict,
  tanggal_pembayaran date not null default current_date,
  jumlah_pembayaran numeric(14, 2) not null check (jumlah_pembayaran > 0),
